//! An 8x8 constant-100 greyscale JPEG. A constant image is exactly
//! representable (only a DC coefficient), so this must decode bit-exactly.
TEST(JpegDecoder, GraySolidConstantDecodesExactly) {
  const std::vector<std::uint8_t> jpeg(
      std::begin(kGraySolid100), std::end(kGraySolid100));
  const DecodedImage image = expect_ok(jpeg);
  EXPECT_EQ(image.width, 8U);
  EXPECT_EQ(image.height, 8U);
  ASSERT_EQ(image.rgba.size(), 8U * 8U * 4U);
  for (std::size_t i = 0; i < 64U; ++i) {
    const std::uint8_t* px = image.rgba.data() + i * 4U;
    EXPECT_EQ(px[0], 100) << "pixel " << i << " r";
    EXPECT_EQ(px[1], 100) << "pixel " << i << " g";
    EXPECT_EQ(px[2], 100) << "pixel " << i << " b";
    EXPECT_EQ(px[3], 255) << "pixel " << i << " a (JPEG is opaque)";
  }
}

//! A 16x16 red/green/blue linear ramp (4:4:4). Smooth gradients keep JPEG
//! error tiny; bound mean-absolute and worst-case per-channel error against
//! the analytic source (compression noise only, no colour-space bug).
TEST(JpegDecoder, ColorGradient16MatchesSourceWithinLossyTolerance) {
  const std::vector<std::uint8_t> jpeg(
      std::begin(kColorGradient16), std::end(kColorGradient16));
  const DecodedImage image = expect_ok(jpeg);
  EXPECT_EQ(image.width, 16U);
  EXPECT_EQ(image.height, 16U);
  ASSERT_EQ(image.rgba.size(), 16U * 16U * 4U);

  std::array<double, 3> error_sum{};
  std::array<int, 3> error_max{};
  std::array<std::size_t, 3> violations{};
  for (std::uint32_t y = 0; y < 16U; ++y) {
    for (std::uint32_t x = 0; x < 16U; ++x) {
      // Analytic source pixels (same truncation the generator used):
      // R = 17x, G = 17y, B = 255(x+y)/30 (integer division).
      const int src[3] = {static_cast<int>(x) * 17,
                          static_cast<int>(y) * 17,
                          255 * (static_cast<int>(x) + static_cast<int>(y)) / 30};
      const std::uint8_t* px =
          image.rgba.data() + (static_cast<std::size_t>(y) * 16U + x) * 4U;
      for (std::size_t c = 0; c < 3; ++c) {
        const int diff = std::abs(static_cast<int>(px[c]) - src[c]);
        error_sum[c] += diff;
        error_max[c] = std::max(error_max[c], diff);
        if (diff > 20) ++violations[c];
      }
      EXPECT_EQ(px[3], 255U);
    }
  }
  for (std::size_t c = 0; c < 3; ++c) {
    EXPECT_LT(error_sum[c] / 256.0, 4.0) << "mean abs error, channel " << c;
    EXPECT_LE(error_max[c], 20) << "worst-case error, channel " << c;
    EXPECT_EQ(violations[c], 0U) << "pixels beyond tolerance, channel " << c;
  }
}

//! A 32x32 two-colour image (red left half, blue right half) saved with 4:2:0
//! chroma subsampling, exercising the triangle ("fancy") chroma upsampler.
//! Asserting regional colour means catches channel swaps, wrong Cb/Cr mapping
//! or broken upsampling without depending on float-IDCT rounding boundaries.
TEST(JpegDecoder, ChromaSubsampled420RedBlueRegionMeans) {
  const std::vector<std::uint8_t> jpeg(
      std::begin(kRedBlue420), std::end(kRedBlue420));
  const DecodedImage image = expect_ok(jpeg);
  EXPECT_EQ(image.width, 32U);
  EXPECT_EQ(image.height, 32U);
  ASSERT_EQ(image.rgba.size(), 32U * 32U * 4U);

  std::array<double, 3> left{};
  std::array<double, 3> right{};
  std::size_t count = 0;
  for (std::uint32_t y = 0; y < 32U; ++y) {
    for (std::uint32_t x = 0; x < 32U; ++x) {
      const std::uint8_t* px =
          image.rgba.data() + (static_cast<std::size_t>(y) * 32U + x) * 4U;
      EXPECT_EQ(px[3], 255U);
      std::array<double, 3>& acc = (x < 16U) ? left : right;
      for (std::size_t c = 0; c < 3; ++c) acc[c] += px[c];
      ++count;
    }
  }
  for (std::size_t c = 0; c < 3; ++c) {
    left[c] /= static_cast<double>(count / 2);
    right[c] /= static_cast<double>(count / 2);
  }
  // Red half: strong R, weak G/B (a little chroma bleed at the seam is fine).
  EXPECT_GT(left[0], 200.0) << "red region mean R";
  EXPECT_LT(left[1], 60.0) << "red region mean G";
  EXPECT_LT(left[2], 80.0) << "red region mean B";
  // Blue half: strong B, weak R/G.
  EXPECT_LT(right[0], 60.0) << "blue region mean R";
  EXPECT_LT(right[1], 60.0) << "blue region mean G";
  EXPECT_GT(right[2], 200.0) << "blue region mean B";
}

TEST(JpegDecoder, DecodingIsDeterministic) {
  const std::vector<std::uint8_t> jpeg(
      std::begin(kColorGradient16), std::end(kColorGradient16));
  const DecodedImage first = expect_ok(jpeg);
  const DecodedImage second = expect_ok(jpeg);
  EXPECT_EQ(first.rgba, second.rgba);
}

