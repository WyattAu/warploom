// decode_image() magic-byte dispatch
// ============================================================================

TEST(JpegDecoder, DecodeImageDispatchRoutesJpegPayloads) {
  const std::vector<std::uint8_t> jpeg(
      std::begin(kGraySolid100), std::end(kGraySolid100));
  std::string error;
  auto result = decode_image(jpeg.data(), jpeg.size(), &error);
  EXPECT_TRUE(result.is_ok()) << "decode failed: " << error;
  ASSERT_TRUE(result.is_ok());
  EXPECT_EQ(result.value().width, 8U);
}

TEST(JpegDecoder, DecodeImageDispatchRejectsUnknownMagic) {
  const std::vector<std::uint8_t> unknown = {0x00, 0x01, 0x02, 0x03,
                                             0x04, 0x05, 0x06, 0x07};
  std::string error;
  auto result = decode_image(unknown.data(), unknown.size(), &error);
  EXPECT_EQ(result.error(), RuntimeError::malformed_asset);
  EXPECT_NE(error.find("neither"), std::string::npos) << error;
}
