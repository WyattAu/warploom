DecodedImage expect_ok(const std::vector<std::uint8_t>& jpeg) {
  std::string error;
  auto result = decode_jpeg(jpeg.data(), jpeg.size(), &error);
  EXPECT_TRUE(result.is_ok()) << "decode failed: " << error;
  if (!result.is_ok()) return DecodedImage{};
  EXPECT_TRUE(result.value().valid());
  return std::move(result).value();
}

void expect_malformed(const std::vector<std::uint8_t>& jpeg,
                      const char* message_fragment = nullptr) {
  std::string error;
  auto result = decode_jpeg(jpeg.data(), jpeg.size(), &error);
  EXPECT_EQ(result.error(), RuntimeError::malformed_asset);
  if (message_fragment != nullptr) {
    EXPECT_NE(error.find(message_fragment), std::string::npos)
        << "expected error mentioning \"" << message_fragment
        << "\" but got: " << error;
  } else {
    EXPECT_FALSE(error.empty()) << "expected a diagnostic message";
  }
}

//! Offset of the SOF0 marker (FF C0). In these encodings the first FF C0
//! sequence is genuinely the frame header (0xFF00 stuffing only applies
//! inside entropy-coded scan data, which starts later).
std::size_t find_sof0(const std::vector<std::uint8_t>& jpeg) {
  for (std::size_t i = 2; i + 1 < jpeg.size(); ++i) {
    if (jpeg[i] == 0xFFU && jpeg[i + 1] == 0xC0U) return i;
  }
  return jpeg.size();
}

